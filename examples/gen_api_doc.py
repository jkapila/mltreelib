"""Generate the per-class API reference from the built module's docstrings.

    uv run python examples/gen_api_doc.py

Writes docs/reference/api/{index,data,model-tree,metrics,encoders,features}.md
— one page per first-class class group, signatures + docstrings straight
from the Rust docstrings (the single source of truth). Output is
regenerated wholesale; do not edit the files by hand.
"""

import inspect
from pathlib import Path

import mltreelib

OUT = Path("docs/reference/api")

ENCODERS = [
    "BaseNEncoder", "CatBoostEncoder", "CountEncoder", "EmbeddingEncoder",
    "HashingEncoder", "JamesSteinEncoder", "LeaveOneOutEncoder",
    "MEstimatorEncoder", "OneHotEncoder", "QuantileEncoder", "SumEncoder",
    "TargetEncoder", "TfidfEncoder", "WoEEncoder",
]

PAGES = [
    ("data.md", "Data",
     ["DatasetBuilder"],
     ["generate", "load_dataset", "list_datasets", "summarize", "winnow"],
     "Typed ingest, the synthetic generator, dataset helpers and column "
     "screening. Guide with real examples: [Data](../data.md)."),
    ("model-tree.md", "ModelTree",
     ["ModelTree"], [],
     "The model tree: typed fit, split-search knobs, quantiles, training "
     "log. Guide: [Model](../model.md)."),
    ("metrics.md", "Metrics",
     ["Metrics"], [],
     "Complete evaluation reports at once. Guides: [Metrics](../metrics.md), "
     "[Evaluation reports](../reports.md)."),
    ("encoders.md", "Encoders & scalers",
     ["IndexMapper", "VariableScaler", "GroupedScaler"] + ENCODERS, [],
     "Pipeline tools for feeding downstream algorithms (sklearn and "
     "friends) — never invoked by the tree. Guide: [Data](../data.md)."),
    ("features.md", "Feature functions",
     [],
     ["grouped_scale", "grouped_transform", "trended_transform",
      "windowed_transform", "lag_by_days", "decomposed_transform",
      "calendar_features"],
     "Grouped/trended/windowed transforms, lags and calendar parts. Guide: "
     "[Data processing](../../examples/data-processing.md)."),
]

HEADER = "<!-- generated by examples/gen_api_doc.py from the built module's docstrings - do not edit -->\n"


def sig(obj):
    try:
        return f"({inspect.signature(obj)})"
    except (ValueError, TypeError):
        return "(...)"


def emit_class(buf, name, cls):
    buf.append(f"## {name}\n")
    buf.append("```python")
    buf.append(f"class {name}{sig(cls)}")
    buf.append("```\n")
    doc = inspect.getdoc(cls)
    if doc:
        buf.append(doc + "\n")
    for mname, m in inspect.getmembers(cls, lambda o: callable(o) and not isinstance(o, type)):
        if mname.startswith("_"):
            continue
        buf.append(f"### {name}.{mname}\n")
        buf.append("```python")
        buf.append(f"{mname}{sig(m)}")
        buf.append("```\n")
        mdoc = inspect.getdoc(m)
        if mdoc:
            buf.append(mdoc + "\n")


def emit_fn(buf, name, fn):
    buf.append(f"## {name}\n")
    buf.append("```python")
    buf.append(f"{name}{sig(fn)}")
    buf.append("```\n")
    doc = inspect.getdoc(fn)
    if doc:
        buf.append(doc + "\n")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    classes = {n: c for n, c in inspect.getmembers(mltreelib, inspect.isclass)
               if not n.startswith("_")}
    fns = {n: f for n, f in inspect.getmembers(
        mltreelib, lambda o: callable(o) and not isinstance(o, type))
        if not n.startswith("_")}

    index = [
        "# API reference — class index\n",
        "\n",
        HEADER,
        "\n",
        "Every class and function with its exact signature and docstring —\n",
        "regenerated from the built module, so this never drifts from the\n",
        "code. Narrative guides with verified examples:\n",
        "[Data](../data.md) · [Model](../model.md) · [Metrics](../metrics.md) ·\n",
        "[Reports](../reports.md) · [Visualization](../plots.md).\n",
        "\n",
        "| page | classes | functions |\n|---|---|---|\n",
    ]
    for fname, title, cl, fn, _blurb in PAGES:
        index.append(
            f"| [{title}]({fname[:-3]}/) | {', '.join(cl) if cl else '—'} "
            f"| {', '.join(fn) if fn else '—'} |\n"
        )
    (OUT / "index.md").write_text("".join(index))

    for fname, title, cl, fn, blurb in PAGES:
        buf = [f"# API reference — {title}\n", "\n", HEADER, "\n", blurb, "\n"]
        for name in fn:
            if name in fns:
                emit_fn(buf, name, fns[name])
        for name in cl:
            if name in classes:
                emit_class(buf, name, classes[name])
        (OUT / fname).write_text("".join(buf))
        print(f"wrote {OUT / fname} ({len(buf)} blocks)")
    print(f"wrote {OUT / 'index.md'}")


if __name__ == "__main__":
    main()
