"""Generate docs/reference/api.md from the built binding's introspection.

    uv run python examples/gen_api_doc.py

Walks the top-level `mltreelib` namespace, emitting each class and method
with its real signature and docstring - the same contract the tests pin.
Output is regenerated wholesale; do not edit the file by hand.
"""

import inspect
from pathlib import Path

import mltreelib

OUT = Path("docs/reference/api.md")


def sig(obj):
    try:
        return f"({inspect.signature(obj)})"
    except (ValueError, TypeError):
        return "(...)"


def emit_class(buf, name, cls):
    buf.append(f"### {name}\n")
    buf.append("```python")
    buf.append(f"class {name}{sig(cls)}")
    buf.append("```\n")
    doc = inspect.getdoc(cls)
    if doc:
        buf.append(doc + "\n")
    for mname, m in inspect.getmembers(cls, lambda o: callable(o) and not isinstance(o, type)):
        if mname.startswith("_"):
            continue
        buf.append(f"#### {name}.{mname}\n")
        buf.append("```python")
        buf.append(f"{mname}{sig(m)}")
        buf.append("```\n")
        mdoc = inspect.getdoc(m)
        if mdoc:
            buf.append(mdoc + "\n")


def main():
    buf = [
        "# API reference — full listing\n",
        "\n",
        "Generated by `examples/gen_api_doc.py` (built-module introspection) —\n",
        "do not edit. Every constructor and method with its exact signature and\n",
        "docstring: the complete `mltreelib` surface. Narrative guides:\n",
        "[Data](data.md) · [Model](model.md) · [Metrics](metrics.md) ·\n",
        "[Visualization](plots.md).\n",
    ]
    # module-level functions first (definition order)
    for name, fn in inspect.getmembers(mltreelib, lambda o: callable(o) and not isinstance(o, type)):
        if name.startswith("_"):
            continue
        buf.append(f"### {name}\n")
        buf.append("```python")
        buf.append(f"{name}{sig(fn)}")
        buf.append("```\n")
        doc = inspect.getdoc(fn)
        if doc:
            buf.append(doc + "\n")
    # classes (definition order where the module preserves it)
    for name, cls in inspect.getmembers(mltreelib, inspect.isclass):
        if name.startswith("_"):
            continue
        emit_class(buf, name, cls)

    OUT.write_text("\n".join(buf))
    print(f"wrote {OUT} ({len(buf)} blocks)")


if __name__ == "__main__":
    main()
