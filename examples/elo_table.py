"""Elo board -> docs: a TabArena-style wide table plus an interactive view.

Reads benchmarks/elo_scores.csv, recomputes the Elo rating (same protocol as
elo_report.py: round-robin on per-dataset RMSE, K=32, start 1000) and writes
docs/benchmarks/elo_board.md - a wide model x dataset RMSE table (best per
dataset bolded) followed by a self-contained sortable HTML table (no external
scripts - the sort is 20 lines of vanilla JS).

    uv run python examples/elo_table.py
"""

import csv
import itertools
from pathlib import Path

OUT = Path("benchmarks/elo_scores.csv")
DOC = Path("docs/benchmarks/elo_board.md")


def main():
    rows = [r for r in csv.DictReader(open(OUT)) if r["model"] != "model"]
    by = {(r["dataset"], r["model"]): (float(r["rmse"]), float(r["mae"]))
          for r in rows}
    datasets = sorted({d for (d, _) in by})
    models = sorted({m for (_, m) in by})

    ratings = {m: 1000.0 for m in models}
    k = 32.0
    for ds in datasets:
        here = {m: v[0] for (d, m), v in by.items() if d == ds}
        for a, b in itertools.combinations(sorted(here), 2):
            sa = 1.0 if here[a] < here[b] else (0.0 if here[a] > here[b] else 0.5)
            ea = 1.0 / (1.0 + 10 ** ((ratings[b] - ratings[a]) / 400.0))
            ratings[a] += k * (sa - ea)
            ratings[b] += k * ((1.0 - sa) - (1.0 - ea))
    order = sorted(models, key=lambda m: -ratings[m])

    def short(ds):
        return ds[3:] if ds.startswith("ta_") else ds

    best = {ds: min(v[0] for (d, _), v in by.items() if d == ds) for ds in datasets}

    # ---- wide markdown table (TabArena style) --------------------------
    lines = []
    lines.append("| Elo | model | " + " | ".join(short(d) for d in datasets) + " |")
    lines.append("|---:|---| " + "|".join("---:" for _ in datasets) + " |")
    for m in order:
        cells = []
        for ds in datasets:
            v = by.get((ds, m))
            if v is None:
                cells.append("·")
            else:
                cells.append(f"**{v[0]:.2f}**" if v[0] == best[ds] else f"{v[0]:.2f}")
        n = sum(1 for (d, mm) in by if mm == m)
        lines.append(f"| {ratings[m]:.0f} | {m} ({n}/{len(datasets)}) | " + " | ".join(cells) + " |")

    # ---- interactive sortable table (self-contained) -------------------
    head = "".join(f"<th data-t='{i}'>{short(d)}</th>" for i, d in enumerate(datasets))
    body_rows = []
    for m in order:
        tds = []
        for ds in datasets:
            v = by.get((ds, m))
            tds.append(f"<td>{v[0]:.2f}</td>" if v is not None else "<td>·</td>")
        body_rows.append(
            f"<tr><td class=n>{ratings[m]:.0f}</td><td class=n><b>{m}</b></td>{''.join(tds)}</tr>"
        )
    html = f"""
<div id="elo-interactive">
<style>
#elo-interactive {{ overflow-x: auto; }}
#elo-interactive table {{ border-collapse: collapse; font-size: 0.78rem; white-space: nowrap; }}
#elo-interactive th, #elo-interactive td {{ padding: 2px 8px; border-bottom: 1px solid var(--md-default-fg-color--lightest, #ddd); text-align: right; }}
#elo-interactive th {{ cursor: pointer; user-select: none; position: sticky; top: 0; background: var(--md-default-bg-color, #fff); }}
#elo-interactive th:hover {{ color: var(--md-accent-fg-color, #06c); }}
#elo-interactive td.n {{ text-align: left; }}
#elo-interactive tr:hover td {{ background: var(--md-default-fg-color--lightest, #f5f5f5); }}
</style>
<table>
<thead><tr><th data-t="-1">Elo</th><th data-t="-2">model</th>{head}</tr></thead>
<tbody>{''.join(body_rows)}</tbody>
</table>
<script>
(function () {{
  var t = document.querySelector('#elo-interactive table');
  if (!t) return;
  var dir = {{}};
  t.querySelectorAll('th').forEach(function (th) {{
    th.addEventListener('click', function () {{
      var i = +th.dataset.t, d = dir[i] = -(dir[i] || 1);
      var rows = Array.prototype.slice.call(t.tBodies[0].rows);
      rows.sort(function (a, b) {{
        var x = a.cells[i + 2].textContent, y = b.cells[i + 2].textContent;
        var nx = parseFloat(x), ny = parseFloat(y);
        return d * (isNaN(nx) || isNaN(ny) ? x.localeCompare(y) : nx - ny);
      }});
      rows.forEach(function (r) {{ t.tBodies[0].appendChild(r); }});
    }});
  }});
}})();
</script>
</div>
"""

    DOC.write_text(
        "<!-- generated by examples/elo_table.py - do not edit by hand -->\n\n"
        + "\n".join(lines)
        + "\n\n### Interactive\n\nClick any column header to sort.\n\n"
        + html
    )
    print(f"wrote {DOC} ({len(datasets)} datasets x {len(models)} models)")


if __name__ == "__main__":
    main()
