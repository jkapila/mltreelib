"""Generate docs/reference/api.md from the live mltreelib API.

The docstrings of the Rust-backed symbols live inside the compiled `_core`
extension, which static documentation tools cannot read. This script renders
them at runtime — the generated file is tracked in git; regenerate after API
changes:

    uv run python scripts/gen_api_docs.py
"""

from __future__ import annotations

import inspect
from pathlib import Path

import mltreelib

OUT = Path(__file__).resolve().parents[1] / "docs" / "reference" / "api.md"
HEADER = "<!-- generated by scripts/gen_api_docs.py — do not edit by hand -->\n\n"

# Sections in presentation order; anything not listed lands in "Other".
GROUPS: list[tuple[str, list[str]]] = [
    ("Data layer", ["DatasetBuilder", "IndexMapper"]),
    (
        "Categorical encoders",
        [
            "OneHotEncoder",
            "HashingEncoder",
            "BaseNEncoder",
            "CountEncoder",
            "SumEncoder",
            "TargetEncoder",
            "MEstimatorEncoder",
            "LeaveOneOutEncoder",
            "CatBoostEncoder",
            "QuantileEncoder",
            "JamesSteinEncoder",
            "TfidfEncoder",
            "WoEEncoder",
            "EmbeddingEncoder",
        ],
    ),
    (
        "Feature transforms",
        ["GroupedScaler", "VariableScaler", "grouped_scale", "grouped_transform", "summarize"],
    ),
    (
        "Time features",
        ["calendar_features", "lag_by_days", "trended_transform", "decomposed_transform", "windowed_transform"],
    ),
    ("Benchmark generator", ["generate"]),
    ("Datasets", ["list_datasets", "load_dataset"]),
]


def signature(obj) -> str:
    try:
        return f"{obj.__name__}{inspect.signature(obj)}"
    except (ValueError, TypeError):
        return f"{obj.__name__}(....)"


def render(name: str, obj, level: int) -> list[str]:
    hashes = "#" * level
    out = [f"{hashes} {name}", ""]
    kind = "class" if inspect.isclass(obj) else "def"
    out += [f"```python", f"{kind} {signature(obj)}", "```", ""]
    out += [inspect.getdoc(obj) or "_(no docstring)_", ""]

    if inspect.isclass(obj):
        for mname, method in sorted(vars(obj).items()):
            if mname.startswith("_"):
                continue
            doc = inspect.getdoc(method)
            out += [f"{hashes}# {name}.{mname}", ""]
            out += [f"```python", f"{signature(method)}", "```", ""]
            out += [doc or "_(no docstring)_", ""]
    return out


def main() -> None:
    lines = [HEADER, "# API reference", ""]
    by_name = {name: getattr(mltreelib, name) for name in mltreelib.__all__}
    seen: set[str] = set()

    for title, names in GROUPS:
        members = [n for n in names if n in by_name]
        if not members:
            continue
        lines += [f"## {title}", ""]
        for name in members:
            lines += render(name, by_name[name], 3)
            seen.add(name)

    rest = [n for n in mltreelib.__all__ if n not in seen]
    if rest:
        lines += ["## Other", ""]
        for name in rest:
            lines += render(name, by_name[name], 3)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
